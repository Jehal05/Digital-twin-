import { useEffect, useMemo, useRef, useState } from "react";
import type { Condition, Prediction } from "../api/types";
import { LineChart } from "../components/charts/Charts";
import { Logo } from "../components/layout/Logo";
import { DigitalTwin } from "../components/twin/DigitalTwin";
import { Button } from "../components/ui/Button";
import { CardTitle, Glass } from "../components/ui/Glass";
import { SelectField } from "../components/ui/Field";
import { featureLabel } from "../lib/format";
import { loadDeviceModel, predictOnDevice, type DeviceModel } from "../lib/onDevice";
import { PERSONAS, SERIES_LABEL, generate, inputsOn, type SeriesKey } from "../lib/simulation";

const DAYS = 90;
const SPEEDS = [{ label: "Slow", ms: 900 }, { label: "Normal", ms: 350 }, { label: "Fast", ms: 90 }];

function asPrediction(condition: Condition, m: DeviceModel, inputs: Record<string, number>, day: number): Prediction {
  const r = predictOnDevice(m, inputs);
  return { id: `sim-${condition}-${day}`, content_kind: "ai_estimate", condition, score: r.score, risk_band: r.band,
    model: { version: m.version, algorithm: "logistic_regression" }, input_snapshot: inputs, trust: null, limitations: ["SIMULATED patient. Not real data."],
    created_at: new Date().toISOString(),
    explanation: { method: "linear", output: "logit", base_value: 0, note: "Simulated", top_drivers: r.drivers.slice(0, 3).map((d) => ({
      feature: d.feature, label: featureLabel(d.feature, d.feature), value: inputs[d.feature], unit: "", effect: d.effect, direction: d.effect > 0 ? "raises" : "lowers" })) } } as Prediction;
}

/** Public page, no account: a synthetic patient whose daily readings animate the twin, the anomaly detector and the time machine. */
export function VirtualPatientPage() {
  const [pid, setPid] = useState(PERSONAS[0].id);
  const persona = PERSONAS.find((p) => p.id === pid)!;
  const readings = useMemo(() => generate(persona, DAYS), [persona]);
  const [day, setDay] = useState(0);
  const [playing, setPlaying] = useState(false);
  const [speed, setSpeed] = useState(1);
  const [models, setModels] = useState<{ diabetes: DeviceModel; heart_disease: DeviceModel } | null>(null);
  const [err, setErr] = useState(false);
  const timer = useRef<number | undefined>(undefined);

  useEffect(() => { Promise.all([loadDeviceModel("diabetes"), loadDeviceModel("heart_disease")]).then(([d, h]) => setModels({ diabetes: d, heart_disease: h })).catch(() => setErr(true)); }, []);
  useEffect(() => { setDay(0); setPlaying(false); }, [pid]);
  useEffect(() => {
    if (!playing) return;
    timer.current = window.setInterval(() => setDay((d) => { if (d >= DAYS) { setPlaying(false); return d; } return d + 1; }), SPEEDS[speed].ms);
    return () => window.clearInterval(timer.current);
  }, [playing, speed]);

  const history = useMemo(() => {
    if (!models) return null;
    return Array.from({ length: day + 1 }, (_, d) => {
      const inp = inputsOn(persona, readings, d);
      return { d, diabetes: predictOnDevice(models.diabetes, inp.diabetes).score, heart: predictOnDevice(models.heart_disease, inp.heart_disease).score };
    });
  }, [models, persona, readings, day]);
  const now = models ? inputsOn(persona, readings, day) : null;
  const predictions: Record<Condition, Prediction | null> = {
    diabetes: models && now ? asPrediction("diabetes", models.diabetes, now.diabetes, day) : null,
    heart_disease: models && now ? asPrediction("heart_disease", models.heart_disease, now.heart_disease, day) : null,
    diabetes_survey: null,
  };
  const flagged = readings.filter((r) => r.day <= day && r.flagged);
  const today = readings.filter((r) => r.day === day);

  return (
    <main className="mx-auto max-w-5xl space-y-4 px-4 py-6">
      <div className="glass flex items-center gap-2.5 px-5 py-3"><Logo /><span className="text-lg font-bold">HealthTwin</span>
        <span className="ml-auto rounded-full bg-moderate-bg px-3 py-1 text-xs font-bold uppercase tracking-wide text-moderate" data-testid="simulated-badge">Simulated patient · not real data</span></div>
      <Glass className="p-5" aria-label="Virtual patient controls">
        <CardTitle>Virtual patient</CardTitle>
        <p className="text-sm text-muted">A made-up person whose readings are generated by a random process with realistic day-to-day variation, a trend and a few planted sensor glitches. The same models and the same anomaly rule used for real accounts run on them. Nothing here is real, saved or sent anywhere.</p>
        <div className="mt-3 grid items-end gap-3 sm:grid-cols-[1fr_auto]">
          <SelectField label="Patient" value={pid} onChange={(e) => setPid(e.target.value)} hint={persona.blurb}>{PERSONAS.map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}</SelectField>
          <div className="flex flex-wrap items-center gap-2">
            <Button onClick={() => setPlaying((p) => !p)} disabled={!models || day >= DAYS}>{playing ? "Pause" : day === 0 ? "Start" : "Resume"}</Button>
            <Button variant="ghost" onClick={() => setDay((d) => Math.min(DAYS, d + 1))} disabled={!models || day >= DAYS}>Next day</Button>
            <Button variant="ghost" onClick={() => { setDay(0); setPlaying(false); }}>Restart</Button>
            <label className="text-sm">Speed <select value={speed} onChange={(e) => setSpeed(Number(e.target.value))} className="ml-1 rounded-lg border border-field bg-card px-2 py-1">{SPEEDS.map((s, i) => <option key={s.label} value={i}>{s.label}</option>)}</select></label>
          </div>
        </div>
        <p className="num mt-3 text-sm" aria-live="polite" data-testid="sim-day">Day {day} of {DAYS}</p>
        <input type="range" min={0} max={DAYS} value={day} onChange={(e) => { setPlaying(false); setDay(Number(e.target.value)); }} aria-label="Simulation day" className="w-full" />
        {err && <p role="alert" className="text-sm text-high">The model files could not be loaded.</p>}
      </Glass>

      <div className="grid gap-4 lg:grid-cols-2">
        {models ? <DigitalTwin predictions={predictions} available={["diabetes", "heart_disease"]} onSelect={() => {}} onRun={() => {}} /> : <Glass className="p-5">Loading models…</Glass>}
        <div className="space-y-4">
          <Glass className="p-5" aria-label="Today's simulated readings">
            <CardTitle>Today's readings <span className="text-xs font-normal text-muted">(simulated)</span></CardTitle>
            <table className="w-full text-left text-sm"><caption className="sr-only">Simulated readings for day {day}</caption>
              <tbody>{today.map((r) => (
                <tr key={r.series} className="border-t border-line"><th scope="row" className="py-1.5 font-normal">{SERIES_LABEL[r.series as SeriesKey]}</th>
                  <td className="num font-semibold">{r.value}</td>
                  <td>{r.flagged && <span className="rounded-full bg-moderate-bg px-2 py-0.5 text-xs font-semibold text-moderate">Flagged: {r.reason}</span>}</td></tr>))}</tbody></table>
          </Glass>
          <Glass className="p-5" aria-label="Anomaly detection" data-testid="anomalies">
            <CardTitle>Anomaly detection <span className="text-xs font-normal text-muted">{flagged.length} flagged so far</span></CardTitle>
            {flagged.length === 0 ? <p className="text-sm text-muted">Nothing unusual yet.</p> : (
              <ul className="space-y-1 text-sm">{flagged.slice(-6).reverse().map((r) => (
                <li key={`${r.day}-${r.series}`}>Day {r.day}: {SERIES_LABEL[r.series]} = <span className="num font-semibold">{r.value}</span> · {r.reason}{r.planted ? <span className="text-muted"> (planted: {r.planted})</span> : null}</li>))}</ul>)}
            <p className="mt-2 text-xs text-muted">Flags are cautions for review, not diagnoses. A flagged reading could be a typing error, a sensor fault or a real change.</p>
          </Glass>
        </div>
      </div>

      {history && history.length > 1 && (
        <div className="grid gap-4 md:grid-cols-2">
          {([["Diabetes estimate over time", "diabetes"], ["Heart disease estimate over time", "heart"]] as const).map(([title, key]) => (
            <Glass key={key} className="p-5" aria-label={title}>
              <CardTitle>{title} <span className="text-xs font-normal text-muted">(Time Machine, simulated)</span></CardTitle>
              <LineChart title={title} xLabel="Day" yLabel="Estimated probability" points={history.map((h) => ({ x: h.d, y: h[key] * 100, label: `day ${h.d}` }))} ymin={0} />
            </Glass>))}
        </div>)}
      <p className="text-center text-xs text-muted">Experimental model estimates on simulated data. Not a diagnosis.</p>
    </main>
  );
}
